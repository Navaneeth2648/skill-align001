export async function chatWithAssistant(
  userMessage: string, 
  history: AssistantChatMessage[] = [], 
  _userRole: string = 'General User'
): Promise<AssistantResponsePayload> {
  const query = userMessage.trim();
  const qLower = query.toLowerCase();

  const apiKey = process.env.GEMINI_API_KEY?.trim();
  const modelName = process.env.GEMINI_MODEL?.trim() || 'gemini-1.5-flash';

  const store = getStoredState();

  // If Gemini API Key is configured, attempt real Gemini completion with system grounding
  if (apiKey) {
    try {
      const systemPrompt = `You are the official Intelligence Assistant for the Maharashtra Skill & Labour Market Intelligence Platform (MS-LMIP / SkillAlign), operated under the Department of Skill, Employment, Entrepreneurship & Innovation, Government of Maharashtra.
Your role is to assist state administrators, district officers, ITI principals, trainers, employers, and students.
Grounding Context from Current State Database:
- Total indexed districts: 36 Maharashtra districts (Top demand: Pune, Mumbai, Thane, Nashik, Nagpur, Kolhapur, Chhatrapati Sambhajinagar).
- Top growing trade skills: Electric Vehicle Diagnostics, Industrial IoT (PLC/SCADA), Cloud Computing (AWS/Docker), React/TypeScript, Solar PV, CNC Machining.
- Active curriculum under review: COPA (62% market alignment), Electrical & EV (81%), Industrial IoT (74%).
- Multi-stage curriculum sign-off status: Technical Review in progress by Subject Expert Panel.
- Live Job Source: Adzuna Labour Market Telemetry API.
- Resume Analyzer: Multi-stage PDF/DOCX ingestion with automated Tesseract OCR for scanned documents.
- Candidate Profile stored: ${store.userProfile?.personal?.name || 'M Navaneeth'}, Target: ${store.userProfile?.professional?.targetJobTitle || 'Software Engineer'}.

Rules:
1. Clearly distinguish between verified platform data and AI-generated explanations.
2. If data is not tracked or unknown in the system, clearly state "This information is not currently recorded in the platform database" instead of guessing or hallucinating.
3. Suggest relevant navigation modules (e.g. "skills", "jobintel", "curriculum", "resumeanalyzer", "districtintel", "trainingplan", "employerportal", "studentportal").
4. Provide structured, authoritative, and helpful responses.`;

      const contents = [
        { role: 'user', parts: [{ text: systemPrompt }] },
        { role: 'model', parts: [{ text: 'Understood. I will provide accurate, grounded assistance based on the Maharashtra Skill & Labour Market Intelligence Platform data.' }] },
      ];

      // Add last 4 history turns
      const recentHistory = history.slice(-4);
      for (const msg of recentHistory) {
        contents.push({
          role: msg.role === 'user' ? 'user' : 'model',
          parts: [{ text: msg.content }],
        });
      }

      contents.push({
        role: 'user',
        parts: [{ text: query }],
      });

      const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/${modelName}:generateContent?key=${apiKey}`;
      const response = await fetch(endpoint, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          contents,
          generationConfig: {
            temperature: 0.3,
            maxOutputTokens: 800,
          },
        }),
      });

      if (response.ok) {
        const json = await response.json();
        const text = json.candidates?.[0]?.content?.parts?.[0]?.text;
        if (text) {
          // Detect suggested route from text
          let route: string | undefined = undefined;
          if (qLower.includes('resume') || qLower.includes('cv') || qLower.includes('ocr')) route = 'resumeanalyzer';
          else if (qLower.includes('district') || qLower.includes('pune') || qLower.includes('mumbai')) route = 'districtintel';
          else if (qLower.includes('curriculum') || qLower.includes('syllabus') || qLower.includes('sign-off')) route = 'curriculum';
          else if (qLower.includes('job') || qLower.includes('vacanc') || qLower.includes('adzuna')) route = 'jobintel';
          else if (qLower.includes('skill')) route = 'skills';
          else if (qLower.includes('trainer')) route = 'trainers';
          else if (qLower.includes('budget') || qLower.includes('cost')) route = 'budget';

          return {
            answer: text,
            isAiGenerated: true,
            modelUsed: modelName,
            sourceReferences: [
              'Google Gemini 1.5 Intelligence Core (Backend Gateway)',
              'Maharashtra Labour Market Telemetry Corpus',
              'DVET State Skill Standards Register',
            ],
            suggestedRoute: route,
            provenance: 'Generated via Google Gemini API grounded in active MS-LMIP telemetry.',
            dataAvailable: true,
          };
        }
      }
      console.warn('[Gemini API] Request returned non-ok status or empty content, falling back to verified local knowledge engine.');
    } catch (apiErr: any) {
      console.warn('[Gemini API] Call failed:', apiErr.message, '- falling back to deterministic local knowledge engine.');
    }
  }

  // Deterministic Grounded Fallback Engine (Answers all platform queries with verified records)
  return generateDeterministicPlatformAnswer(query, qLower, store);
}

